export function WeatherIcon({ condition = 'Clear', isNight = false, size = 32, className = '' }) {
  const c = condition.toLowerCase();
  if (c.includes('thunder') || c.includes('storm')) return <ThunderIcon size={size} className={className} />;
  if (c.includes('rain') || c.includes('drizzle') || c.includes('shower')) return <RainIcon size={size} className={className} />;
  if (c.includes('snow') || c.includes('sleet')) return <SnowIcon size={size} className={className} />;
  if (c.includes('cloud') || c.includes('overcast')) return <CloudIcon size={size} className={className} />;
  return isNight ? <MoonIcon size={size} className={className} /> : <SunIcon size={size} className={className} />;
}
